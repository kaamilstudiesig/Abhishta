"use client";

import { useEffect, useId, useRef, useState } from "react";
import { Icon360, IconChevronLeft, IconChevronRight, IconExpand, IconExternal } from "@/components/icons";
import { TOUR_360_URL } from "@/lib/site";
import { tourUrl, type Tour } from "@/lib/tour";

/** The parts of Turiya's Pano2VR player this viewer uses. */
type Player = {
  setBasePath(path: string): void;
  readConfigString(xml: string): void;
  openNext(node: string, view?: string): void;
  toggleFullscreen(): void;
  startAutorotate(speed?: number, resumeAfterSeconds?: number): void;
  stopAutorotate(): void;
  addListener(event: string, callback: () => void): void;
};
type PlayerConstructor = new (containerId: string, options?: object) => Player;

declare global {
  interface Window {
    pano2vrPlayer?: PlayerConstructor;
  }
}

/** Turiya's own player script (it sends CORS headers, as do the image tiles). */
const PLAYER_SRC = `${TOUR_360_URL}pano2vr_player.js`;
/** The scenes the site shows, hotspots stripped, wheel/keyboard locked — generated by `npm run tour:scenes`. */
const CONFIG_SRC = "/tour/scenes.xml";
/** A slow turn, as on Peninsula del Mar's room views; it pauses while you drag and picks up again after a few seconds. */
const SPIN_SPEED = 0.1;
const SPIN_RESUME_AFTER_S = 4;

type Loaded = {
  Player: PlayerConstructor;
  config: string;
  /** Turiya's scene ids (customnodeid) → the player's own ids; the player only learns the former after loading. */
  ids: Record<string, string>;
};
let loading: Promise<Loaded> | null = null;

/** Loads the player script and the scenes config once per page, however many viewers there are. */
function loadPlayer() {
  loading ??= Promise.all([
    new Promise<PlayerConstructor>((resolve, reject) => {
      if (window.pano2vrPlayer) return resolve(window.pano2vrPlayer);
      const script = document.createElement("script");
      script.src = PLAYER_SRC;
      script.async = true;
      script.onload = () => (window.pano2vrPlayer ? resolve(window.pano2vrPlayer) : reject(new Error("no player")));
      script.onerror = () => reject(new Error("player failed to load"));
      document.head.appendChild(script);
    }),
    fetch(CONFIG_SRC).then((r) => {
      if (!r.ok) throw new Error(`config ${r.status}`);
      return r.text();
    }),
  ])
    .then(([Player, config]) => {
      const ids: Record<string, string> = {};
      for (const scene of config.match(/<panorama\b[\s\S]*?<\/panorama>/g) ?? []) {
        const id = scene.match(/<panorama\b[^>]*\bid="([^"]+)"/)?.[1];
        const custom = scene.match(/customnodeid="([^"]+)"/)?.[1];
        if (id && custom) ids[custom] = id;
      }
      return { Player, config, ids };
    })
    .catch((error) => {
      loading = null; // let a later viewer try again
      throw error;
    });
  return loading;
}

const viewOf = (tour: Tour) => `${tour.pan}/${tour.tilt}/75`;
const sceneOf = (tour: Tour, ids: Record<string, string>) => `{${ids[tour.node] ?? tour.node}}`;
const motionAllowed = () => !window.matchMedia("(prefers-reduced-motion: reduce)").matches;

type Tone = "light" | "dark";

/**
 * A live 360° scene from the farm's Turiya tour, drawn on our page by Turiya's
 * own Pano2VR player but without Turiya's skin — no START card, logo or menu.
 * It turns slowly on its own (not with reduced motion, and only while on
 * screen), stops while you drag and turns again a few seconds after you let
 * go. The mouse wheel scrolls the page, never zooms. The player starts as the
 * viewer nears the screen; a new `tour` turns the same player to that scene.
 * Optional prev/next arrows and a caption, as on Peninsula del Mar's views.
 * Controls keep to the sides and bottom corners; the top corners stay free.
 *
 * Always embed the tour this way — never as an iframe (that brings Turiya's
 * START card and chrome back). See docs/BUILDING_PAGES.md.
 */
export function TourViewer({
  tour,
  title,
  tone,
  caption,
  onPrev,
  onNext,
  prevLabel = "Previous view",
  nextLabel = "Next view",
  className = "",
}: {
  tour: Tour;
  /** accessible name, e.g. "360° view inside Mayura cottage" */
  title: string;
  tone: Tone;
  /** shown on the view, top left */
  caption?: string;
  onPrev?: () => void;
  onNext?: () => void;
  prevLabel?: string;
  nextLabel?: string;
  className?: string;
}) {
  const containerId = `tour-${useId().replace(/[^a-zA-Z0-9_-]/g, "")}`;
  const wrapRef = useRef<HTMLDivElement>(null);
  const playerRef = useRef<Player | null>(null);
  const idsRef = useRef<Record<string, string>>({});
  const tourRef = useRef(tour);
  const onScreenRef = useRef(false);
  const [status, setStatus] = useState<"waiting" | "loading" | "ready" | "error">("waiting");
  const [touched, setTouched] = useState(false);
  const [canFullscreen, setCanFullscreen] = useState(false);
  const dark = tone === "dark";

  useEffect(() => {
    const wrap = wrapRef.current;
    if (!wrap) return;
    let alive = true;

    const spin = () => {
      const player = playerRef.current;
      if (!player) return;
      if (onScreenRef.current && motionAllowed()) player.startAutorotate(SPIN_SPEED, SPIN_RESUME_AFTER_S);
      else player.stopAutorotate();
    };

    // start the player once it's near the screen
    const near = new IntersectionObserver(
      ([entry]) => {
        if (!entry.isIntersecting) return;
        near.disconnect();
        setStatus("loading");
        setCanFullscreen(!!document.fullscreenEnabled);
        loadPlayer()
          .then(({ Player, config, ids }) => {
            if (!alive) return;
            idsRef.current = ids;
            const player = new Player(containerId);
            player.setBasePath(TOUR_360_URL);
            player.addListener("imagesready", () => alive && setStatus("ready"));
            player.addListener("changenode", spin); // every scene picks up the slow turn
            player.readConfigString(config);
            playerRef.current = player;
            player.openNext(sceneOf(tourRef.current, ids), viewOf(tourRef.current));
          })
          .catch(() => alive && setStatus("error"));
      },
      { rootMargin: "100% 0px" },
    );
    // turn only while it's actually on screen
    const visible = new IntersectionObserver(([entry]) => {
      onScreenRef.current = entry.isIntersecting;
      spin();
    });
    near.observe(wrap);
    visible.observe(wrap);

    const host = document.getElementById(containerId);
    return () => {
      alive = false;
      near.disconnect();
      visible.disconnect();
      playerRef.current?.stopAutorotate();
      playerRef.current = null;
      host?.replaceChildren(); // drop the player's canvas so it stops drawing
    };
  }, [containerId]);

  // a new scene: turn the same player to it (and remember it for a player that's still loading)
  useEffect(() => {
    tourRef.current = tour;
    playerRef.current?.openNext(sceneOf(tour, idsRef.current), viewOf(tour));
  }, [tour]);

  const control =
    "z-10 grid size-[40px] place-items-center rounded-full bg-ink/45 text-paper backdrop-blur-[2px] transition-colors duration-300 hover:bg-ink/70";

  return (
    <div
      ref={wrapRef}
      role="group"
      aria-label={title}
      className={`relative isolate overflow-hidden rounded-card ${dark ? "bg-paper/[0.06] ring-1 ring-paper/10" : "bg-card ring-1 ring-line"} ${className}`}
    >
      <p
        role="status"
        className={`absolute inset-0 grid place-items-center px-s21 text-center text-[15px] ${dark ? "text-paper/70" : "text-ink-muted"}`}
      >
        {status === "error" ? (
          <span>
            The 360° view didn’t load.{" "}
            <a href={tourUrl(tour.node, tour)} target="_blank" rel="noopener noreferrer" className="underline underline-offset-4">
              Open it in the tour
            </a>
          </span>
        ) : status === "ready" ? null : (
          "Opening the 360° view…"
        )}
      </p>

      {/* the player draws in here (it handles mouse and touch: drag to look around) */}
      <div id={containerId} onPointerDown={() => setTouched(true)} className="absolute inset-0 cursor-grab active:cursor-grabbing" />

      {status === "ready" ? (
        <>
          {/* bottom left: the drag cue until the first drag, then the caption (the top corners stay clear for page decoration) */}
          <span className="pointer-events-none absolute bottom-s13 left-s13 z-10 flex flex-col items-start gap-[6px]">
            {!touched ? (
              <span className="inline-flex items-center gap-[6px] rounded-btn bg-ink/45 px-s13 py-[7px] text-[13px] font-medium text-paper backdrop-blur-[2px]">
                <Icon360 size={18} />
                Drag to look around
              </span>
            ) : null}
            {caption ? (
              <span className="rounded-btn bg-ink/45 px-s13 py-[6px] text-[13px] font-medium text-paper backdrop-blur-[2px]">{caption}</span>
            ) : null}
          </span>
          {canFullscreen ? (
            <button
              type="button"
              onClick={() => playerRef.current?.toggleFullscreen()}
              aria-label="Show full screen"
              className={`absolute right-s13 bottom-s13 ${control}`}
            >
              <IconExpand size={18} />
            </button>
          ) : null}
          {onPrev ? (
            <button type="button" onClick={onPrev} aria-label={prevLabel} className={`absolute top-1/2 left-s13 -translate-y-1/2 ${control}`}>
              <IconChevronLeft size={20} />
            </button>
          ) : null}
          {onNext ? (
            <button type="button" onClick={onNext} aria-label={nextLabel} className={`absolute top-1/2 right-s13 -translate-y-1/2 ${control}`}>
              <IconChevronRight size={20} />
            </button>
          ) : null}
        </>
      ) : null}
    </div>
  );
}

/** Desktop hint under a viewer, with a way into the whole tour. */
export function TourLink({ tour, tone, lead, className = "" }: { tour: Tour; tone: Tone; lead?: string; className?: string }) {
  const dark = tone === "dark";
  return (
    <p className={`flex flex-wrap items-center gap-x-s21 gap-y-[2px] text-[14px] ${dark ? "text-paper/75" : "text-ink-muted"} ${className}`}>
      {lead ? <span>{lead}</span> : null}
      <a
        href={tourUrl(tour.node, tour)}
        target="_blank"
        rel="noopener noreferrer"
        className={`tap inline-flex items-center gap-[6px] font-medium ${dark ? "text-paper hover:text-gold" : "text-forest hover:text-farm"}`}
      >
        Walk the whole farm in 360°
        <IconExternal size={16} />
        <span className="sr-only">(opens the tour in a new tab)</span>
      </a>
    </p>
  );
}
